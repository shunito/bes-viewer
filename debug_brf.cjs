const chars = [];
for(let i=0;i<text.length;i++){
  const c=text[i];
  if(c==='\r') continue;
  else if(c==='\n') chars.push('@LB@');
  else if(c==='\f') chars.push('@PB@');
  else chars.push(map[c] || ('[0x'+c.charCodeAt(0).toString(16)+']'));
}
console.log(chars.join('').substring(0,1000));
